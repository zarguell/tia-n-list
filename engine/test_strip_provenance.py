#!/usr/bin/env python3
"""Digest provenance-trailer contract (audit 2026-10-26).

Owner decision 4526f2c5a49d: internal model/token accounting must never reach
a reader-facing page. Cronman's wrapper stopped appending the trailer on
2026-10-25, but the 2026-10-26 audit found 50 stored digests (2026-09-07 ..
2026-10-26) whose trailer still rendered on /daily/<date>/ — the wrapper's
checkout had been stale for five days, so the fix was not in effect for the
digests it composed. The strip lives at render time so a lagging deploy can
never publish model accounting again.

  1. a trailing "Generated by …" paragraph is removed with or without a blank
     line before it, including the "(token counts unavailable)" and
     "Composed from …" variants;
  2. prose that merely mentions the phrase mid-paragraph survives;
  3. clean digests are unchanged apart from trailing whitespace;
  4. the strip is idempotent;
  5. no shipped digest in engine/data/digests renders a trailer.
"""
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ssg

FAILS = []


def check(name, cond, detail=""):
    if cond:
        print(f"ok   {name}")
    else:
        print(f"FAIL {name} {detail}")
        FAILS.append(name)


strip = ssg.strip_provenance

check("trailer after blank line is dropped",
      strip("[NEW] Prose.\n\nGenerated by opencode-go/x. Input tokens: 1, "
            "output tokens: 2, cache read: 3, cache write: 0.\n")
      == "[NEW] Prose.\n")
check("trailer with no blank line is dropped",
      strip("[NEW] Prose.\nGenerated by zai/glm-9. Composed from the "
            "deterministic digest-candidates brief.\n") == "[NEW] Prose.\n")
check("token-counts-unavailable variant is dropped",
      strip("Prose.\n\nGenerated by opencode-go/m (token counts "
            "unavailable).\n") == "Prose.\n")
check("mid-paragraph mention survives",
      strip("[NEW] Tool stamps 'Generated by' into metadata.\n\n"
            "Watchlist: rotate keys.\n")
      == "[NEW] Tool stamps 'Generated by' into metadata.\n\n"
         "Watchlist: rotate keys.\n")
check("clean digest keeps its body",
      strip("[NEW] Prose.\n\nWatchlist: patch CVE-2026-1 now.\n")
      == "[NEW] Prose.\n\nWatchlist: patch CVE-2026-1 now.\n")
body = strip("[NEW] Prose.\n\nGenerated by opencode-go/x.\n")
check("strip is idempotent", strip(body) == body)

here = os.path.dirname(os.path.abspath(__file__))
leaks = [os.path.basename(f)
         for f in glob.glob(os.path.join(here, "data", "digests", "*.md"))
         if "Generated by" in strip(open(f).read())]
check("no shipped digest renders a trailer", not leaks, str(leaks[:3]))

print()
if FAILS:
    print(f"FAILED: {len(FAILS)} check(s): {', '.join(FAILS)}")
    sys.exit(1)
print("all digest provenance-trailer contract checks passed")
